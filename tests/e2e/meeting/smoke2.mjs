import { launch, newPerson, login, createMeeting, openRoom, guestSignIn, press, waitPhase, shot, closeAll, sleep, assertFlow, tiles, rtcSnapshot } from './lib.mjs';
const browser = await launch();
try {
  const host = await newPerson(browser, { name: 'Naledi', kind: 'host' });
  const g1 = await newPerson(browser, { name: 'Thandi', email: 'thandi@karoofresh.example' });
  await login(host);
  const key = await createMeeting(host, 'Smoke 2');
  await openRoom(host, key);
  console.log('host phase', await press(host));
  await waitPhase(host, 'live');
  await guestSignIn(g1, key);
  await openRoom(g1, key);
  console.log('guest phase', await press(g1));
  await sleep(1500);
  console.log('host banner', await host.page.evaluate(() => document.getElementById('banner').innerText), host.page.url());
  console.log('title', await host.page.title());
  await shot(host, 'smoke2-host-waiting.png');
  await host.page.click('#banner button:has-text("Admit")');
  await waitPhase(g1, 'live', 20000);
  console.log('guest live');
  await sleep(8000);
  console.log('tiles host', JSON.stringify(await tiles(host.page)));
  console.log('tiles guest', JSON.stringify(await tiles(g1.page)));
  console.log(JSON.stringify(await rtcSnapshot(host.page)));
  console.log('video els', JSON.stringify(await host.page.evaluate(() => [...document.querySelectorAll('#grid video')].map(v => ({ paused: v.paused, rs: v.readyState, muted: v.muted, tracks: v.srcObject ? v.srcObject.getTracks().map(t => t.kind + ':' + t.readyState + ':' + t.muted + ':' + t.enabled) : null })))));
  console.log(await assertFlow(host.page, { peers: 1, label: 'host' }));
  console.log(await assertFlow(g1.page, { peers: 1, label: 'guest' }));
  await shot(host, 'smoke2-host.png'); await shot(g1, 'smoke2-guest.png');
  console.log('host errs', host.errors, 'guest errs', g1.errors);
} catch (e) { console.error('FAILED', e); } finally { await closeAll(); await browser.close(); }
